import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { loadEnv } from "vite";

const mode = process.argv[2] || "production";
const projectRoot = process.cwd();
const outputDirectory = path.join(projectRoot, "dist");
const outputPath = path.join(outputDirectory, ".env");
const publicEnvironment = loadEnv(mode, projectRoot, "VITE_");

const serializedEnvironment = Object.keys(publicEnvironment)
  .filter((key) => /^VITE_[A-Z0-9_]+$/.test(key))
  .sort()
  .map((key) => `${key}=${JSON.stringify(publicEnvironment[key])}`);

const contents = [
  "# Generated by npm run build.",
  "# VITE_ variables are public and were already embedded in the client bundle.",
  "# Rebuild the app after changing these values; static hosting does not reload this file at runtime.",
  ...serializedEnvironment,
  "",
].join("\n");

await mkdir(outputDirectory, { recursive: true });
await writeFile(outputPath, contents, "utf8");

console.log(
  `Wrote ${path.relative(projectRoot, outputPath)} with ${serializedEnvironment.length} public environment variables.`,
);
